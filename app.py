"""# **Netoyer TEXTE retouner par mistral**"""

import re
def nettoyer_reponse(texte):

    # Supprimer les titres Markdown : # ## ###
    texte = re.sub(
        r'^\s*#+\s*',
        '',
        texte,
        flags=re.MULTILINE
    )

    # Supprimer les astérisques
    texte = texte.replace("*", "")

    # Supprimer les underscores utilisés pour l'italique
    texte = texte.replace("_", "")

    # Supprimer les backticks
    texte = texte.replace("`", "")

    # Supprimer les chevrons de citation Markdown
    texte = re.sub(
        r'^\s*>\s?',
        '',
        texte,
        flags=re.MULTILINE
    )

    # Nettoyer les espaces multiples
    texte = re.sub(
        r' {2,}',
        ' ',
        texte
    )

    return texte.strip()

