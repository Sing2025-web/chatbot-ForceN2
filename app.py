########   Decoupage du document en chucks
def charger_et_decouper(texte, taille=CHUNK_SIZE, overlap=CHUNK_OVERLAP):
    import re

    if texte is None:
        raise ValueError(f"Impossible de lire le fichier")

    # Nettoyage
    texte = re.sub(r'\n{3,}', '\n\n', texte).strip()
    print(f"Taille du texte : {len(texte)} caracteres")

    # Securite anti-boucle infinie
    if overlap >= taille:
        raise ValueError(f"overlap ({overlap}) doit etre inferieur a taille ({taille})")

    # Decoupage avec chevauchement
    chunks, debut, idx = [], 0, 0
    while debut < len(texte):
        fin = min(debut + taille, len(texte))
        if fin < len(texte):
            coupe = texte.rfind('.', debut, fin)
            if coupe > debut:
                fin = coupe + 1
        chunk = texte[debut:fin].strip()
        if chunk:
            chunks.append({"id": f"chunk_{idx:04d}", "texte": chunk})
            idx += 1
        nouveau_debut = fin - overlap
        if nouveau_debut <= debut:   # securite absolue anti-boucle infinie
            nouveau_debut = debut + 1
        debut = nouveau_debut

    return chunks


