#fonction pour interoger chromadb avec la question de l'utilisateur
def recherche(question):
    #transformer la question en vecteur
    question_embedding = embedding(question)

    #interrogeons chromadb
    result = collection.query(

        query_embeddings=[
            question_embedding
        ],

        n_results=3,
        include=["documents", "distances"]
    )

    return result["documents"][0]



